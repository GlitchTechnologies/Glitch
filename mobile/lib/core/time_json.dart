/// ## Правило
///
/// Пишем — [utcIso]. Читаем — [parseUtcLocal]. Внутри приложения `DateTime`
/// всегда МЕСТНОЕ, в JSON всегда UTC. Третьего варианта нет.
///
/// ## Зачем понадобилось (реальный баг, 2026-08-23)
///
/// Разъехались они так. Сервер присылает время в UTC, но без буквы `Z` на
/// конце. Читающая сторона это знает: не видит `Z` — дописывает сама и
/// переводит в местное. А вот кэш сохранял уже переведённое, МЕСТНОЕ время
/// обычным `toIso8601String()` — который у местного времени никакой пометки о
/// зоне не ставит вовсе. При следующем чтении строка снова выглядела как «UTC
/// без Z», и к ней ВТОРОЙ раз прибавлялся сдвиг часового пояса.
///
/// ## Почему пара, а не «просто исправить запись»
library;

/// В JSON — всегда UTC с явной `Z` на конце.
///
/// Именно `toUtc()` перед сериализацией: у местного времени
/// `toIso8601String()` не пишет ни `Z`, ни смещения, и прочитать такую строку
/// однозначно уже нельзя.
String utcIso(DateTime value) => value.toUtc().toIso8601String();

/// Строка без `Z` и без смещения считается UTC: так их присылает сервер
/// (`datetime.isoformat()` в Python пишет наивное время без зоны). Наш
/// собственный кэш такие уже не пишет — см. [utcIso], — но старые записи,
/// сохранённые до 2026-08-23, ещё могут лежать на устройствах, и ронять их
/// разбор нельзя.
DateTime parseUtcLocal(dynamic raw) {
  if (raw == null) return DateTime.now();
  String str = raw as String;
  if (!str.endsWith('Z') && !str.contains('+')) str = '${str}Z';
  return DateTime.parse(str).toLocal();
}
